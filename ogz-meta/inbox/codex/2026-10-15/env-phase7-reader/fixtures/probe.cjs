"use strict";
const fs=require('fs'),path=require('path'),vm=require('vm'),assert=require('assert/strict');
const source=fs.readFileSync('ogz-meta/pipeline-phase7-handoff.js','utf8');
const ast=require('@babel/parser').parse(source,{sourceType:'script'});
const selected=ast.program.body.filter(n=>n.type==='FunctionDeclaration'&&['checkConfigConsistency','checkNumericSanity'].includes(n.id.name));
assert.equal(selected.length,2);
const code=selected.map(n=>source.slice(n.start,n.end)).join('\n');
assert(!/envVars|\.env|readFileSync/.test(code));
const real=require(path.resolve('foundation/ConfigLoader'));
let calls=[],logs=[];
const context=vm.createContext({ConfigLoader:real,JSON_OUT:false,section(){},check:(...a)=>calls.push(a),console:{log:s=>logs.push(s)}});
vm.runInContext(code+'\ncheckConfigConsistency();checkNumericSanity();',context);
const contracts=real.getConfigFileValue('exitContracts');
for(const name of Object.keys(contracts))assert(logs.some(s=>s.startsWith('  '+name+':')));
assert(logs.some(s=>s.includes('proposed trade size')));
assert(calls.every(c=>!c[1].includes('R:R')&&!c[1].includes('fee')));
calls=[];logs=[];
context.ConfigLoader={getConfigFileValue:()=>({Disabled:{profitManagement:{tieredExit:{enabled:false}},tpMode:'off',takeProfitPercent:null,maxHoldMode:'off'},Active:{profitManagement:{tieredExit:{enabled:true,profitTiers:{tier1:0.02,tier2:0.01,tier3:0.03,final:0.04}}},tpMode:'percent',takeProfitPercent:1}})};
vm.runInContext('checkConfigConsistency();checkNumericSanity();',context);
assert(!calls.some(c=>c[1].startsWith('Disabled')));
assert(calls.some(c=>c[1]==='Active active tier targets in ascending order'&&c[2]===false));
assert(logs.some(s=>s.includes('target=off/null')));
logs=[];context.JSON_OUT=true;vm.runInContext('checkNumericSanity();',context);assert.equal(logs.length,0);
const result={pass:true,checks:['raw canonical file contracts reported individually without runtime claim','JSON mode emits no numeric console output','raw dotenv parsing removed from both config functions','disabled tier policy ignored as intended','active tier order check preserved','no global R:R/15m/fee recommendation','fees explicitly require proposed size'],limits:['Only changed functions executed; full legacy phase7 tool not run','No trading numbers or production policy changed']};
fs.writeFileSync(path.join(__dirname,'../verification.json'),JSON.stringify(result,null,2)+'\n');console.log(JSON.stringify(result));
